#!/usr/bin/env python3
"""Bundle semantic locale resources; runtime needs no translation service."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / 'spk/package/ui'
catalogs = {p.stem: json.loads(p.read_text()) for p in sorted((UI / 'locales').glob('*.json'))}
(UI / 'locales.js').write_text('/* Generated by scripts/build-presentation.py. */\n(function(root){const catalogs=' + json.dumps(catalogs,ensure_ascii=False,separators=(',',':')) + ';if(typeof module!=="undefined"&&module.exports)module.exports=catalogs;else root.NetBirdLocales=catalogs;})(typeof window!=="undefined"?window:globalThis);\n')
